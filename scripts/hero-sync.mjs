#!/usr/bin/env node
// Syncs shopify-theme/assets/slideshow/ to the Shopify theme used by the Hero slideshow.
// Images -> theme assets (hero-slide-NN-<hash>.<ext>); order list -> snippets/gira-hero-slides.liquid.
// Usage: node scripts/hero-sync.mjs [--watch] [--dry-run]
// Env:   SHOPIFY_STORE (default giragiraglasses.myshopify.com), HERO_THEME_ID (default live theme),
//        SHOPIFY_CLI_THEME_TOKEN (Theme Access password; required in CI, optional locally after `shopify auth`).
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { appendFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, watch, copyFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const THEME_DIR = join(ROOT, 'shopify-theme');
const IMAGE_DIR = join(THEME_DIR, 'assets', 'slideshow');
const LOG_FILE = join(ROOT, 'logs', 'hero-sync.log');
const MANIFEST = join(THEME_DIR, 'snippets', 'gira-hero-slides.liquid');
const STORE = process.env.SHOPIFY_STORE || 'giragiraglasses.myshopify.com';
const THEME_ID = process.env.HERO_THEME_ID || '167141834835';
const EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const MAX_SLIDES = 20;
const MAX_BYTES = 20 * 1024 * 1024;
const RETRIES = 3;
const args = new Set(process.argv.slice(2));

const log = (level, message) => {
  const line = `${new Date().toISOString()} [${level}] ${message}`;
  console.log(line);
  try {
    mkdirSync(dirname(LOG_FILE), { recursive: true });
    appendFileSync(LOG_FILE, `${line}\n`);
  } catch { /* logging must never break the sync */ }
};

const collectImages = () => {
  if (!existsSync(IMAGE_DIR)) return [];
  const files = readdirSync(IMAGE_DIR, { withFileTypes: true })
    .filter((entry) => entry.isFile() && EXTENSIONS.has(extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true, sensitivity: 'base' }));
  const seen = new Map();
  const images = [];
  for (const name of files) {
    const path = join(IMAGE_DIR, name);
    const size = statSync(path).size;
    if (size === 0 || size > MAX_BYTES) { log('WARN', `skip ${name}: size ${size} bytes is not usable (max 20MB)`); continue; }
    const hash = createHash('sha1').update(readFileSync(path)).digest('hex').slice(0, 8);
    if (seen.has(hash)) { log('WARN', `skip ${name}: identical to ${seen.get(hash)}`); continue; }
    seen.set(hash, name);
    images.push({ name, path, hash, ext: extname(name).toLowerCase().replace('.jpeg', '.jpg') });
  }
  if (images.length > MAX_SLIDES) log('WARN', `${images.length} images found; only the first ${MAX_SLIDES} are used`);
  return images.slice(0, MAX_SLIDES);
};

const shopify = (extra) => {
  const base = ['theme', 'push', '--store', STORE, '--theme', THEME_ID, '--path', THEME_DIR, '--allow-live'];
  for (let attempt = 1; attempt <= RETRIES; attempt += 1) {
    const result = spawnSync('shopify', [...base, ...extra], { shell: process.platform === 'win32', encoding: 'utf8', env: { ...process.env, NO_COLOR: '1', SHOPIFY_CLI_NO_ANALYTICS: '1' } });
    if (result.status === 0) return;
    const output = `${result.stdout || ''}${result.stderr || ''}`.trim().split('\n').slice(-6).join(' | ');
    log('ERROR', `shopify push failed (attempt ${attempt}/${RETRIES}): ${output}`);
    if (attempt < RETRIES) Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 3000 * attempt);
  }
  throw new Error('shopify theme push failed after retries');
};

const generatedAssets = () => {
  const dir = join(THEME_DIR, 'assets');
  return existsSync(dir) ? readdirSync(dir).filter((file) => /^hero-slide-\d+-[0-9a-f]{8}\.(jpg|png|webp)$/.test(file)) : [];
};

const sync = () => {
  const images = collectImages();
  const names = images.map((image, index) => `hero-slide-${String(index + 1).padStart(2, '0')}-${image.hash}${image.ext}`);
  log('INFO', `${images.length} image(s): ${images.map((image) => image.name).join(', ') || '(none, fallback hero is used)'}`);
  if (args.has('--dry-run')) { log('INFO', `dry run; would publish: ${names.join(', ')}`); return names; }

  generatedAssets().forEach((file) => rmSync(join(THEME_DIR, 'assets', file)));
  images.forEach((image, index) => copyFileSync(image.path, join(THEME_DIR, 'assets', names[index])));
  writeFileSync(MANIFEST, `{%- comment -%}Auto-generated by scripts/hero-sync.mjs. Do not edit.{%- endcomment -%}\n${names.join('|')}\n`);

  // 1) upload new images without deleting anything, 2) switch the manifest, 3) delete images that are no longer listed.
  if (names.length) shopify(['--nodelete', ...names.flatMap((name) => ['--only', `assets/${name}`])]);
  shopify(['--nodelete', '--only', 'snippets/gira-hero-slides.liquid']);
  shopify(['--only', 'assets/hero-slide-*']);
  log('INFO', `published ${names.length} slide(s) to theme ${THEME_ID}; verifying public HTML`);
  return names;
};

// Fetches the storefront HTML and compares the rendered slide list with what was published.
const verify = async (expected) => {
  const isLive = THEME_ID === (process.env.HERO_LIVE_THEME_ID || '167141834835');
  const base = process.env.HERO_VERIFY_URL || 'https://www.giraeyewear.com/';
  let last = [];
  for (let attempt = 1; attempt <= 8; attempt += 1) {
    try {
      const url = `${base}?v=${Date.now()}${isLive ? '' : `&preview_theme_id=${THEME_ID}`}`;
      const html = await (await fetch(url, { headers: { 'user-agent': 'Mozilla/5.0 hero-sync-verify', 'cache-control': 'no-cache' } })).text();
      last = [...new Set([...html.matchAll(/hero-slide-\d+-[0-9a-f]{8}\.(?:jpg|png|webp)/g)].map((m) => m[0]))];
      if (last.join('|') === expected.join('|')) {
        log('INFO', `VERIFIED public site shows ${last.length} slide(s): ${last.join(', ') || '(fallback)'}`);
        return true;
      }
    } catch (error) { last = [`fetch error: ${error.message}`]; }
    await new Promise((r) => setTimeout(r, 5000));
  }
  log('ERROR', `MISMATCH expected [${expected.join(', ')}] but public site shows [${last.join(', ')}]`);
  return false;
};

const run = async () => {
  try {
    const names = sync();
    return args.has('--dry-run') ? true : await verify(names);
  } catch (error) { log('ERROR', error.message); return false; }
};

if (args.has('--watch')) {
  mkdirSync(IMAGE_DIR, { recursive: true });
  log('INFO', `watching ${IMAGE_DIR}`);
  let timer;
  let running = false;
  let again = false;
  const trigger = () => {
    clearTimeout(timer);
    timer = setTimeout(async () => {
      if (running) { again = true; return; }
      running = true;
      await run();
      running = false;
      if (again) { again = false; trigger(); }
    }, 3000);
  };
  await run();
  watch(IMAGE_DIR, trigger);
} else {
  process.exit((await run()) ? 0 : 1);
}

